# ── Color function ────────────────────────────────────────────────────────────
def val_to_color(raw_val):
    if raw_val is None or (isinstance(raw_val, float) and np.isnan(raw_val)):
        return '#cccccc'
    val = max(VMIN, min(VMAX, to_pct(raw_val)))
    if val <= VMID:
        t = (val - VMIN) / max(VMID - VMIN, 0.001)
        return '#{:02x}{:02x}{:02x}'.format(
            int(26  + (255 - 26)  * t),
            int(152 + (255 - 152) * t),
            int(80  + (191 - 80)  * t))
    else:
        t = (val - VMID) / max(VMAX - VMID, 0.001)
        return '#{:02x}{:02x}{:02x}'.format(
            int(255 + (215 - 255) * t),
            int(255 + (48  - 255) * t),
            int(191 + (39  - 191) * t))

# ── Build JS data ─────────────────────────────────────────────────────────────
