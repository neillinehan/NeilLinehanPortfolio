    df_yearly = df_yearly.merge(census, on='CBSA_Code', how='left')
    df_yearly['Pop_Display'] = df_yearly['Population'].apply(
        lambda x: f"{x/1e6:.2f}M" if pd.notna(x) and x >= 1e6 else (f"{x/1e3:.0f}K" if pd.notna(x) else "N/A"))
    df_yearly['Income_Display'] = df_yearly['Median_HH_Income'].apply(
        lambda x: f"${x:,.0f}" if pd.notna(x) else "N/A")
