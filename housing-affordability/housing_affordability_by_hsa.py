df['Month'] = pd.to_datetime(df['Month'])
df['Year'] = df['Month'].dt.year
df['CBSA_Code'] = df['CBSA_Code'].astype(str).str.zfill(5)
geo_df['GEOID'] = geo_df['GEOID'].astype(str).str.zfill(5)

METRIC = 'Housing_Cost%_of_Med_HHIncome'
CENSUS_YEAR = 2022   # ACS 5-year vintage used for demographics
# ── Census demographics ───────────────────────────────────────────────────────
def fetch_census_cbsa():
    url = (
        "https://api.census.gov/data/2022/acs/acs5"
        "?get=NAME,B01003_001E,B19013_001E"
        "&for=metropolitan+statistical+area/micropolitan+statistical+area:*"
    )
    try:
        r = requests.get(url, timeout=15)
        data = r.json()
        cdf = pd.DataFrame(data[1:], columns=data[0])
        cdf = cdf.rename(columns={
            'metropolitan statistical area/micropolitan statistical area': 'CBSA_Code',
            'B01003_001E': 'Population',
            'B19013_001E': 'Median_HH_Income',
        })
        cdf['CBSA_Code'] = cdf['CBSA_Code'].str.zfill(5)
        cdf['Population'] = pd.to_numeric(cdf['Population'], errors='coerce')
        cdf['Median_HH_Income'] = pd.to_numeric(cdf['Median_HH_Income'], errors='coerce')
        return cdf[['CBSA_Code', 'Population', 'Median_HH_Income']]
    except Exception as e:
        print(f"Census fetch failed: {e}")
        return pd.DataFrame(columns=['CBSA_Code', 'Population', 'Median_HH_Income'])

census = fetch_census_cbsa()

# ── Yearly aggregate ──────────────────────────────────────────────────────────
df_yearly = df.groupby(['CBSA_Code', 'CBSA_Name', 'Year'], as_index=False)[METRIC].mean()
df_yearly[METRIC] = df_yearly[METRIC]#.round(1)
df_yearly['Rank'] = df_yearly.groupby('Year')[METRIC].rank(method='min', ascending=True).astype(int)
df_yearly['N_MSAs'] = df_yearly.groupby('Year')['CBSA_Code'].transform('count')

# ── Cross-time stats ──────────────────────────────────────────────────────────
def cross_stats(g):
    best_idx  = g[METRIC].idxmin()
    worst_idx = g[METRIC].idxmax()
    return pd.Series({
        'Avg_Cost_Pct':   round(g[METRIC].mean(), 1),
        'Best_Year':      f"{int(g.loc[best_idx,  'Year'])} (#{int(g.loc[best_idx,  'Rank'])} of {int(g.loc[best_idx,  'N_MSAs'])})",
        'Best_Cost_Raw':  g.loc[best_idx,  METRIC],
        'Worst_Year':     f"{int(g.loc[worst_idx, 'Year'])} (#{int(g.loc[worst_idx, 'Rank'])} of {int(g.loc[worst_idx, 'N_MSAs'])})",
        'Worst_Cost_Raw': g.loc[worst_idx, METRIC],
    })

try:
    cross_time = df_yearly.groupby('CBSA_Code').apply(cross_stats, include_groups=False)
except TypeError:
    cross_time = df_yearly.groupby('CBSA_Code').apply(cross_stats)

cross_time = cross_time.reset_index()  # CBSA_Code becomes a column
df_yearly = df_yearly.merge(cross_time, on='CBSA_Code')

